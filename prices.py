# Хвосты-исключения в названиях USDA: «..., excludes macaroni and cheese».
# Слова после них означают, чего в блюде НЕТ, и сопоставлять по ним —
# прямая ошибка. Та же ловушка, что в shopping.py.
_EXCLUSION_TAIL = re.compile(r",\s*(excludes|excluding|not)\b.*$", re.IGNORECASE)

# Признаки того, что блюдо НЕ готовили, и множитель веса применять нельзя.
_RAW = re.compile(r"\b(raw|uncooked|dry|dried|fresh)\b", re.IGNORECASE)

_COMPILED_PRIORITY: list[tuple[str, re.Pattern[str]]] = [
    (key, re.compile(pattern, re.IGNORECASE)) for key, pattern in PRIORITY_RULES
]
_COMPILED: list[tuple[str, re.Pattern[str]]] = [
    (key, re.compile(pattern, re.IGNORECASE)) for key, pattern in PRICE_RULES
]


def _match(text: str) -> str | None:
    """Ценовая категория для одной строки описания."""
    cleaned = _EXCLUSION_TAIL.sub("", text)

    for key, pattern in _COMPILED_PRIORITY:
        if pattern.search(cleaned):
            return key

    # Побеждает совпадение, стоящее в названии раньше: в описаниях USDA
    # главный продукт называется первым. При равной позиции — порядок
    # правил в списке, поэтому храним и его.
    best: tuple[int, int, str] | None = None
    for order, (key, pattern) in enumerate(_COMPILED):
        found = pattern.search(cleaned)
        if found is None:
            continue
        candidate = (found.start(), order, key)
        if best is None or candidate < best:
            best = candidate

    return best[2] if best else None


def price_key_for(name: str, category: str = "") -> str | None:
    """К какой ценовой категории отнести блюдо. None — правила не нашлось.

    Сначала пробуем название блюда (оно точнее), потом раздел справочника.
    """
    for source in (name, category):
        if source and (key := _match(source)):
            return key
    return None


def cost_of(grams: float, name: str, category: str = "") -> float | None:
    """Во что обойдётся столько граммов ОДНОГО продукта. None — цены нет.

    Это расчёт по одному названию. Для блюда из справочника точнее считать
    по составу — ``cost_by_composition``; сюда блюдо попадает только когда
    рецептуры для него нет.

    Возвращается именно None, а не ноль: неопознанный продукт не бесплатный,
    он неизвестной стоимости, и разница между этими случаями решающая.
    """
    key = price_key_for(name, category)
    if key is None:
        return None

    price = PRICES[key]

    # Множитель применяем только к приготовленному: «Rice, white, raw»
    # уже лежит в магазине в этом весе.
    yield_factor = 1.0 if _RAW.search(name) else price.cooking_yield

    raw_grams = grams / yield_factor
    return raw_grams / 1000.0 * price.rub_per_kg


def cost_by_composition(grams: float, ingredients) -> tuple[float | None, float]:
    """Стоимость блюда по его рецептуре.

    Точнее расчёта по названию, и ошибку чинит в ОБЕ стороны: у «креветок
    с овощами» креветок 69 г из 200, а у «салата с макаронами и сыром»
    четверть массы — чеддер, который по названию не виден вовсе.

    Args:
        grams: вес порции блюда.
        ingredients: список объектов с полями ``name`` и ``share``
            (``ingredients.Ingredient``). Тип намеренно не импортируется:
            иначе ``prices`` и ``ingredients`` замкнулись бы друг на друга.

    Returns:
        Пару (стоимость, доля массы с известной ценой). Стоимость — None,
        если опознать не удалось ничего.

        Доля возвращается вместе с суммой не для красоты: рецептура может
        состоять из незнакомых строк, и тогда сумма посчитана по крохе
        состава, оставаясь на вид полноценной.
    """
    if not ingredients:
        return None, 0.0

    total = 0.0
    priced_share = 0.0

    for item in ingredients:
        part = cost_of(item.share * grams, item.name)
        if part is None:
            continue
        total += part
        priced_share += item.share

    # Ниже половины состава экстраполировать нельзя: растягивать цену
    # известной трети на всё блюдо — это уже не оценка, а домысел.
    # Лучше честное «не знаю» и откат к расчёту по названию.
    if priced_share < 0.5:
        return None, priced_share

    # Досчитываем по опознанной части: если пятая часть состава без цены,
    # честнее растянуть известную стоимость на весь вес, чем молча отдать
    # сумму за четыре пятых блюда. Допущение здесь одно и названное:
    # неопознанное стоит столько же за грамм, сколько опознанное.
    return total / priced_share, priced_share
