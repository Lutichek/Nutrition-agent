"""
Исправления перевода каталога — все в одном месте.

Названия блюд переводит модель (``translate_catalog.py``), и часть ошибок
она делает устойчиво: переводит пачками, и внутри пачки может уйти в свою
терминологию. Такие ошибки чинятся заменой, а не новым прогоном — словарь
дешевле, быстрее и, в отличие от модели, повторяем.

**Почему отдельный модуль.** Раньше правки жили как придётся: часть
в ``translate_catalog.py``, часть — вообще нигде, применённая разовым
скриптом прямо к parquet. Такая правка держится ровно до первой пересборки
каталога, после чего «Омлет или scrambled eggs» и «Горчица, вареная»
возвращаются молча. Здесь единственный источник правды, и его применяет
всё, что пишет каталог.

Два вида исправлений, потому что ошибки бывают двух видов:

``NAME_FIXES``
    Замена подстроки везде, где она встретится. Годится, когда неверный
    оборот однозначен: «шкура съедена» не значит ничего другого ни в одном
    блюде.

``SCOPED_FIXES``
    Замена только в строках, чьё АНГЛИЙСКОЕ название совпало с шаблоном.
    Нужна, когда то же русское слово в других блюдах верно: «Горчица» —
    правильный перевод для приправы и неправильный для mustard greens,
    которые на самом деле листовой овощ.

Проверка:

    python translation_fixes.py        # что и где будет исправлено
"""

from __future__ import annotations

import pandas as pd

# ── Замены везде ─────────────────────────────────────────────
# Порядок важен: более длинный оборот разбирается раньше короткого,
# иначе первая замена съест часть второй («не съедена» → «съедена»).
NAME_FIXES: list[tuple[str, str]] = [
    # Пометки опроса FNDDS. Справочник записывает, что именно попало
    # в тарелку — от этого зависит состав, — но человеку в названии блюда
    # нужно описание еды, а не протокол: «с кожей», а не «шкура съедена».
    #
    # По-русски у птицы кожа, а не шкура. Модель перевела 134 такие позиции
    # верно, а одну пачку — через «шкуру»; отсюда «Куриное бедро, жареное
    # на гриле без соуса, шкура съедена» в реальном плане пользователя.
    ("шкура/панировка не съедена", "без кожи и панировки"),
    ("шкура/панировка съедена", "с кожей и панировкой"),
    ("шкура не съедена", "без кожи"),
    ("шкура съедена", "с кожей"),
    ("панировка не съедена", "без панировки"),
    ("панировка съедена", "с панировкой"),
    ("без учета съеденного жира", "жирность не уточнена"),
    ("без учёта съеденного жира", "жирность не уточнена"),
    ("Куриная шкурка", "Куриная кожа"),
    ("Картофельные шкурки", "Картофельные лодочки"),

    # Обрывки перевода: пачка не сошлась по размеру, сработал запасной путь,
    # и часть названия осталась английской.
    ("scrambled eggs", "яичница-болтунья"),
    ("кафе кон leche", "кофе с молоком"),
    ("Easy Mac", "макароны быстрого приготовления"),
    ("Hamburger Helper", "смесь для макарон с фаршем"),
]

# ── Замены с оглядкой на оригинал ────────────────────────────
# (шаблон английского названия, что заменить, на что)
SCOPED_FIXES: list[tuple[str, str, str]] = [
    # Rotisserie — это готовка на вертеле. «Роти» — индийская лепёшка,
    # и она в каталоге тоже есть («Bread, chapatti or roti»). Поэтому
    # замена привязана к английскому названию, а не к русскому слову.
    (r"^Chicken .*rotisserie", "роти", "на вертеле"),
    (r"^Turkey .*rotisserie", "роти", "на вертеле"),

    # Mustard greens — листовой овощ, а не приправа. Перевод «Горчица»
    # верен для mustard как приправы и неверен здесь, поэтому правим
    # только строки, где в оригинале именно greens.
    (r"^Mustard greens", "Горчица", "Листовая горчица"),
    (r"^Mustard greens", "Сырая горчица", "Листовая горчица, сырая"),
]


def apply(catalog: pd.DataFrame) -> pd.DataFrame:
    """Применить все исправления к колонке ``name_ru``.

    Идемпотентно: повторный вызов ничего не меняет. Каталог правится
    на месте и возвращается для удобства цепочек.
    """
    if "name_ru" not in catalog.columns:
        return catalog

    names = catalog["name_ru"].astype("string")

    for wrong, right in NAME_FIXES:
        names = names.str.replace(wrong, right, regex=False)

    for pattern, wrong, right in SCOPED_FIXES:
        rows = catalog["name"].str.contains(pattern, regex=True, na=False)
        names = names.mask(rows, names.str.replace(wrong, right, regex=False))

    # «…, роти» в конце строки: запятой справа нет, поэтому отдельно.
    names = names.str.replace(r",\s*роти$", ", на вертеле", regex=True)

    catalog["name_ru"] = names.fillna("")
    return catalog


def report(catalog: pd.DataFrame) -> None:
    """Показать, что именно будет исправлено. Ничего не меняет."""
    before = catalog["name_ru"].copy()
    after = apply(catalog.copy())["name_ru"]

    changed = before != after
    print(f"Будет исправлено названий: {int(changed.sum())} из {len(catalog)}\n")

    for original, fixed in list(zip(before[changed], after[changed], strict=True))[:20]:
        print(f"  {original[:64]}")
        print(f"      → {fixed[:64]}")

    if changed.sum() > 20:
        print(f"\n  ... и ещё {int(changed.sum()) - 20}")


if __name__ == "__main__":  # pragma: no cover
    from foods import load_catalog

    report(load_catalog())
